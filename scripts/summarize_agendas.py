#!/usr/bin/env python3
"""Plain-language summaries of upcoming agendas — the pipeline's one LLM step.

Phase 3 of docs/superpowers/plans/2026-08-13-github-pages-site.md. For each
upcoming/<slug>/ with an agenda-preview.md, generate summary.md using the
self-hosted llama-server (Qwen3.5-35B on slayden), reached through its
token-authed public endpoint.

Shape (2026-09-09): a "What matters most" lead of at most six bullets, then
every remaining item under `###` group headings. Before that the summary was a
flat one-bullet-per-item list — 75 bullets for the 9/10 agenda, 70% as long as
the verbatim topic list it summarizes and with the agenda's own section
structure thrown away. Coverage-first came from a4d197d and is not being
walked back: enumeration still carries every item, the lead is an additional
layer on top. See structure_problems for what is checked.

The layer is strictly additive:

- No SLAYDEN_API_TOKEN -> print a notice and exit 0; the site falls back to
  the deterministic topic list.
- A summary is regenerated only when the preview's content hash changes
  (amended agendas), so unchanged agendas produce no diff.
- Generation failures (server down for gaming, network) warn and exit 0 so
  the Tuesday workflow still commits the deterministic preview artifacts.
- Backlog: meetings/<slug>/ folders holding an agenda-preview.md without a
  matching summary.md (the meeting passed while the LLM was down) are
  backfilled on every run, so the next run with the server up heals the gap.

Model note (measured 2026-08-18 on the Aug 13 agenda): Qwen3.5 MUST run with
thinking disabled here — thinking mode spent the entire output budget on
reasoning and produced no summary; thinking-off completed in ~8 s with an
accurate, hallucination-free bullet list.
"""
from __future__ import annotations

import hashlib
import os
import re
import sys
from datetime import date
from pathlib import Path

import requests

sys.path.insert(0, str(Path(__file__).resolve().parent))
import grounding  # noqa: E402

REPO_ROOT = Path(__file__).resolve().parent.parent
UPCOMING_DIR = REPO_ROOT / "upcoming"
MEETINGS_DIR = REPO_ROOT / "meetings"
PROMPT_PATH = Path(__file__).resolve().parent / "prompts" / "laymans-summary.md"

BASE_URL = os.environ.get("SUMMARY_BASE_URL", "https://slayden-api.duckdns.org")
MODEL = os.environ.get("SUMMARY_MODEL", "qwen3.5-35b")
TIMEOUT = 300

_HASH_RE = re.compile(r"source-sha256: ([0-9a-f]{64})")


def source_hash(preview_md: str) -> str:
    return hashlib.sha256(preview_md.encode("utf-8")).hexdigest()


def summary_is_current(summary_path: Path, preview_md: str) -> bool:
    """True if summary.md exists and was generated from this exact preview."""
    if not summary_path.exists():
        return False
    m = _HASH_RE.search(summary_path.read_text(encoding="utf-8"))
    return m is not None and m.group(1) == source_hash(preview_md)


def render_summary_md(body: str, preview_md: str, generated: str) -> str:
    return (f"<!-- AI-generated ({MODEL}) from agenda-preview.md on {generated}; "
            f"source-sha256: {source_hash(preview_md)} -->\n"
            "## In plain language\n\n"
            f"{body.strip()}\n\n"
            "*This summary was generated by an AI model from the agenda; "
            "check the agenda PDF for the authoritative wording.*\n")


def generate_body(preview_md: str) -> str:
    """One LLM call: agenda preview markdown -> the plain-language summary body.

    OpenAI-compatible endpoint with Qwen thinking disabled via
    chat_template_kwargs — the same recipe the aider config uses.
    """
    prompt = PROMPT_PATH.read_text(encoding="utf-8").replace("{agenda}", preview_md)
    resp = requests.post(
        f"{BASE_URL}/v1/chat/completions",
        headers={"Authorization": f"Bearer {os.environ['SLAYDEN_API_TOKEN']}"},
        json={
            "model": MODEL,
            "max_tokens": 8192,
            "messages": [{"role": "user", "content": prompt}],
            "chat_template_kwargs": {"enable_thinking": False},
        },
        timeout=TIMEOUT)
    resp.raise_for_status()
    choice = resp.json()["choices"][0]
    if choice.get("finish_reason") != "stop":
        raise RuntimeError(f"generation did not finish: {choice.get('finish_reason')}")
    text = (choice["message"].get("content") or "").strip()
    if not text.startswith(("#", "-", "*")):
        raise RuntimeError(f"unexpected summary shape: {text[:120]!r}")
    return text


LEAD_HEADING = "### What matters most"
MAX_LEAD_BULLETS = 6

# Draft budget per meeting. Three rather than two because there are now three
# ways to be wrong (grounding, coverage, shape) and the checks are used to pick
# the best draft, not merely to accept the last one. One meeting a day, ~40 s a
# draft on the local model.
MAX_ATTEMPTS = 3

_HEADING_RE = re.compile(r"^###\s+(.*)$", re.M)
_BULLET_RE = re.compile(r"^[-*]\s+(.*)$", re.M)

# A bare ordinance/resolution number the model volunteered for an item. Banned
# from this summary: see structure_problems. "Ordinance No. 89-79" is allowed
# when it names the thing being amended, which is how the agenda itself uses
# it — the pattern below requires the citation form, so "amending Ordinance No.
# 89-79, Classification and Salary Plan" does not match while "(Ordinance
# 26-830)" and "Resolution No. 26-761." do.
_ITEM_NUMBER_RE = re.compile(
    r"\(\s*(?:Ordinance|Resolution)\s+(?:No\.\s*)?\d{2}-\d{2,4}\s*\)"
    r"|(?:Ordinance|Resolution)\s+(?:No\.\s*)?\d{2}-\d{2,4}\s*(?=[.;,]?\s*$)",
    re.M)

# "the council" as filler after the bold subject, e.g.
# "**Budget amendment** — the council amends ...". Distinct from a bullet that
# OPENS with it; both are boilerplate, and both are checked.
_COUNCIL_FILLER_RE = re.compile(r"—\s*the council\b", re.I)

# Three or more SHOUTED words in a row. The expenditure fund table is all-caps
# ("6.5 MILL SCHOOL PROPERTY TAX") and the model copies it verbatim into the
# summary despite being asked for sentence case. Three-word minimum and a
# 3-letter floor per word so real acronyms in a row - "TIF D8", "US 431",
# "FSA", "LLC" - do not trip it.
_SHOUTING_RE = re.compile(r"\b[A-Z]{3,}(?:\s+[A-Z&.]{3,}){2,}\b")

# A stated count, which the prompt forbids outright: the model has miscounted in
# four separate runs, most recently promising "five separate properties" above a
# list of four. Anchored on a number word plus a countable noun so acreages,
# dates, dollar amounts and "three-year terms" are left alone.
_COUNT_RE = re.compile(
    r"\b(?:two|three|four|five|six|seven|eight|nine|ten|eleven|twelve)\s+"
    r"(?:\w+\s+){0,2}"
    r"(?:hearings|items|properties|parcels|reappointments|appointments|"
    r"contracts|ordinances|resolutions|settlements|agreements|nominations|"
    r"seats|permits|amendments|easements)\b", re.I)


def lead_and_rest(body: str) -> tuple[str, str]:
    """Split a summary body into the lead section and the grouped remainder.

    The split is positional — everything before the SECOND `###` heading is the
    lead — rather than a match on LEAD_HEADING, so a model that renames the
    heading still yields a sane split. Fewer than two headings means the model
    ignored the output shape entirely; the whole body is then the lead and the
    caller renders it as one block, which is what this script did before groups
    existed.
    """
    headings = list(_HEADING_RE.finditer(body))
    if len(headings) < 2:
        return body.strip(), ""
    cut = headings[1].start()
    return body[:cut].strip(), body[cut:].strip()


def structure_report(body: str) -> tuple[list[str], int]:
    """Deviations from the output shape the prompt asks for, and their weight.

    Soft by design, like grounding.uncovered_items: a summary that keeps the
    "The council will vote to" boilerplate is still accurate and still more
    useful to a reader than the fallback topic list, so this warns and gets one
    regeneration rather than blocking publication. Only a fabricated figure or
    name is worth refusing to publish over.

    The second return value counts offending bullets, so two flawed drafts can
    be compared. Both attempts on the 2026-09-10 agenda carried the same single
    problem KIND while one had 38 bad bullets and the other 8; ranking on
    whether the list was empty picked the worse one.
    """
    problems: list[str] = []
    weight = 0
    lead, rest = lead_and_rest(body)

    # A missing shape is one problem but a severe one: nothing else about the
    # draft can be judged, so weight it above any volume of per-bullet nits.
    if not _HEADING_RE.search(body):
        problems.append("no ### headings; expected a lead plus group sections")
        weight += 1000
    elif not rest:
        problems.append("only one ### section; expected a lead plus group sections")
        weight += 1000
    if LEAD_HEADING not in body:
        first = _HEADING_RE.search(body)
        found = f"{first.group(1)!r}" if first else "nothing"
        problems.append(f"lead heading is {found}, expected {LEAD_HEADING!r}")
        weight += 100

    n_lead = len(_BULLET_RE.findall(lead))
    if rest and n_lead > MAX_LEAD_BULLETS:
        problems.append(f"lead has {n_lead} bullets, at most "
                        f"{MAX_LEAD_BULLETS} expected")
        weight += n_lead - MAX_LEAD_BULLETS

    bullets = _BULLET_RE.findall(body)
    boilerplate = [b for b in bullets
                   if b.lstrip("*_ ").lower().startswith("the council")]
    if boilerplate:
        problems.append(f'{len(boilerplate)} bullet(s) open with "The council": '
                        f"{boilerplate[0][:60]!r}")
        weight += len(boilerplate)

    filler = [b for b in bullets if _COUNCIL_FILLER_RE.search(b)]
    if filler:
        problems.append(f'{len(filler)} bullet(s) restate "the council" after '
                        f"the dash: {filler[0][:60]!r}")
        weight += len(filler)

    # Checked mechanically rather than left to the prompt because the failure is
    # invisible downstream: a volunteered number is copied verbatim out of the
    # agenda, so grounding.report sees a legitimate string even when it has been
    # attached to the wrong item. Three were misattributed on the 2026-09-10
    # agenda - a resolution renamed an ordinance, and a salary-schedule bullet
    # carrying the hearing-aid tax exemption's number.
    numbered = [b for b in bullets if _ITEM_NUMBER_RE.search(b)]
    if numbered:
        problems.append(f"{len(numbered)} bullet(s) cite an ordinance/resolution "
                        f"number: {numbered[0][:60]!r}")
        weight += 10 * len(numbered)

    # Weighted like a misattributed number, not like a style nit: a wrong count
    # is a false statement, and the model has never reliably got one right.
    counted = [m.group(0) for b in bullets for m in [_COUNT_RE.search(b)] if m]
    if counted:
        problems.append(f"{len(counted)} bullet(s) state a count: {counted[0]!r}")
        weight += 10 * len(counted)

    shouting = [b for b in bullets if _SHOUTING_RE.search(b)]
    if shouting:
        problems.append(f"{len(shouting)} bullet(s) copy ALL-CAPS source text: "
                        f"{_SHOUTING_RE.search(shouting[0]).group(0)[:40]!r}")
        weight += len(shouting)
    return problems, weight


def structure_problems(body: str) -> list[str]:
    """The shape problems in a draft, without their comparison weight."""
    return structure_report(body)[0]


def _source_md(pdir: Path) -> str:
    """The LLM's full input: agenda preview + attachment excerpts when present.

    Both feed the source hash, so a late-arriving attachments file (or an
    amended agenda) triggers a richer regeneration.
    """
    source = (pdir / "agenda-preview.md").read_text(encoding="utf-8")
    att = pdir / "agenda-attachments.md"
    if att.exists():
        source += "\n\n" + att.read_text(encoding="utf-8")
    return source


def hash_input(source_md: str) -> str:
    """What the source hash covers: the prompt template plus the LLM input.

    Including the prompt means a prompt improvement regenerates the summary for
    an UPCOMING meeting, so the next agenda gets the current instructions. Past
    meetings are frozen once written - see _summarize_dir's backfill_only.
    """
    return PROMPT_PATH.read_text(encoding="utf-8") + source_md


def _generate_grounded(pdir: Path, source: str, preview: str,
                       generate: "callable[[str], str]") -> str:
    """Generate a summary, refusing to publish one that invents a dollar figure.

    Three tiers, because the failures are not equally bad.

    A fabricated dollar figure or company name is worse than no summary at all:
    the site falls back to the verbatim agenda topic list, which is honest, while
    a made-up number on a civic page is not. So those are regenerated, and if no
    attempt is clean nothing is written and the caller logs it.

    Missing agenda items and structural misses (no lead section, an overlong
    lead, bullets still opening with "The council will vote to") are both
    regenerated but neither blocks publication. A partial or ugly summary still
    helps a reader, and the coverage check is a heuristic over word rarity - it
    should not be able to take the page down on its own.

    Coverage outranks shape when choosing between drafts: a resident who never
    learns the council is exempting hearing aids from sales tax is worse off
    than one who reads "the council" a few times too often. That ordering is
    not hypothetical - the grouped shape introduced 2026-09-09 measurably costs
    coverage, and two drafts of the 2026-09-10 agenda dropped one item and four
    items respectively.

    Kept cheap deliberately: at most MAX_ATTEMPTS calls, once a day.
    """
    attempts = []
    for attempt in range(1, MAX_ATTEMPTS + 1):
        body = generate(source)
        hard = grounding.report(body, source)             # figures + names
        shape, weight = structure_report(body)
        soft = grounding.uncovered_items(body, preview)
        attempts.append((body, hard, shape, weight, soft))
        if not hard and not shape and not soft:
            break
        for label, lines in (("not grounded", hard), ("off-shape", shape),
                             ("items not covered",
                              [f"{i} {t[:80]}" for i, t in soft])):
            if lines:
                print(f"warn: {pdir.name}: attempt {attempt} {label}:",
                      file=sys.stderr)
                for line in lines:
                    print(f"  {line}", file=sys.stderr)

    # Prefer a grounded attempt over the merely most recent one; among those the
    # one covering the most agenda items; only then the better-shaped one. A
    # retry is not guaranteed to be the better draft, and when several are
    # flawed the difference is one of degree.
    body, hard, shape, _, soft = min(
        attempts, key=lambda a: (bool(a[1]), len(a[4]), a[3]))
    if hard:
        raise RuntimeError(
            f"{len(hard)} ungrounded claim(s) after {len(attempts)} attempts; "
            f"refusing to publish (site falls back to the topic list)")
    if shape:
        print(f"warn: {pdir.name}: publishing off-shape summary "
              f"({len(shape)} problem(s)) after {len(attempts)} attempts",
              file=sys.stderr)
    if soft:
        print(f"warn: {pdir.name}: {len(soft)} agenda item(s) not covered:",
              file=sys.stderr)
        for item_id, title in soft:
            print(f"  {item_id} {title[:80]}", file=sys.stderr)
    return body


def _summarize_dir(pdir: Path, today: date, generate: "callable[[str], str]",
                   label: str, backfill_only: bool = False) -> None:
    """Write summary.md for one meeting directory.

    backfill_only (past meetings): generate only when there is no summary at
    all. A past meeting's summary is a record of what was published at the
    time - a prompt change must not silently rewrite the archive, and the
    agenda it described can no longer change. Only genuine gaps get filled.

    Otherwise (upcoming meetings): regenerate whenever the hash moves, so an
    amended agenda, a late-arriving attachment, or an improved prompt is
    picked up before the meeting happens.
    """
    if backfill_only and (pdir / "summary.md").exists():
        print(f"ok: {pdir.name}: summary.md exists; past meeting, left as published")
        return
    source = _source_md(pdir)
    hashable = hash_input(source)
    if summary_is_current(pdir / "summary.md", hashable):
        print(f"ok: {pdir.name}: summary.md up to date")
        return
    preview = (pdir / "agenda-preview.md").read_text(encoding="utf-8")
    try:
        body = _generate_grounded(pdir, source, preview, generate)
        (pdir / "summary.md").write_text(
            render_summary_md(body, hashable, today.isoformat()),
            encoding="utf-8")
        print(f"ok: {pdir.name}: wrote summary.md{label}")
    except Exception as exc:  # noqa: BLE001 — LLM layer must never fail the sync
        print(f"warn: {pdir.name}: summary generation failed: {exc}",
              file=sys.stderr)


def summarize(upcoming_dir: Path, meetings_dir: Path | None = None,
              today: date | None = None,
              generate: "callable[[str], str]" = generate_body) -> int:
    if not os.environ.get("SLAYDEN_API_TOKEN"):
        print("SLAYDEN_API_TOKEN not set; skipping plain-language summaries "
              "(the site falls back to the topic list)")
        return 0
    today = today or date.today()
    # upcoming meetings first (site main page), then the backlog of past
    # meetings whose summary was skipped while the LLM was down
    dirs: list[tuple[Path, str, bool]] = []
    if upcoming_dir.exists():
        dirs += [(p, "", False) for p in sorted(upcoming_dir.iterdir()) if p.is_dir()]
    if meetings_dir is not None and meetings_dir.exists():
        dirs += [(p, " (backfilled)", True) for p in sorted(meetings_dir.iterdir())
                 if p.is_dir()]
    todo = [d for d in dirs if (d[0] / "agenda-preview.md").exists()]
    if not todo:
        print("nothing to summarize")
        return 0
    for pdir, label, backfill_only in todo:
        _summarize_dir(pdir, today, generate, label, backfill_only)
    return 0


if __name__ == "__main__":
    sys.exit(summarize(UPCOMING_DIR, MEETINGS_DIR))
